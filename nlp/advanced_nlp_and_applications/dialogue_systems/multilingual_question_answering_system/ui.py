NAVIGATION = [
    "Home",
    "Ask a Question",
    "Translation Studio",
    "Text Summarization",
    "Conversation History",
    "Settings",
]
LANGUAGE_CHOICES = supported_language_names()
ANSWER_LANGUAGES = ["Same as question"] + LANGUAGE_CHOICES
SUMMARY_LANGUAGES = ["Same as input"] + LANGUAGE_CHOICES


def _render_home():
    st.title("Multilingual Question Answering System")
    st.caption(
        "Ask in your language, explore a passage, translate text, or create a summary with Groq."
    )
    summary = get_dashboard_summary()
    metrics = st.columns(2)
    metrics[0].metric("Questions asked", summary["questions"])
    metrics[1].metric("Conversations", summary["conversations"])
    st.subheader("Start exploring")
    cards = st.columns(3)
    cards[0].markdown("#### Ask anything\nGet a multilingual answer with adjustable detail.")
    cards[1].markdown("#### Ask about a text\nChoose general-knowledge or context-only answering.")
    cards[2].markdown("#### Translate or summarize\nUse the same Groq model for supported language tasks.")
    st.subheader("Try a sample question")
    for question in (
        "What is supervised learning?",
        "இயந்திர கற்றல் என்றால் என்ன?",
        "मशीन लर्निंग क्या है?",
        "Explain photosynthesis in simple terms.",
    ):
        st.markdown(f"- {question}")
    recent = list_conversations(limit=5)
    if recent:
        st.subheader("Recent questions")
        for conversation in recent:
            latest_user_message = next(
                (
                    message
                    for message in reversed(get_messages(conversation["id"]))
                    if message["role"] == "user"
                ),
                None,
            )
            if latest_user_message:
                st.markdown(f"- {latest_user_message['content'][:200]}")
    st.info(
        f"Configured model: `{get_groq_model()}`. "
        "Answers are generated by an LLM and may be inaccurate."
    )
    st.caption("Questions sent to Groq are processed by the external Groq API.")


def _select_conversation():
    conversations = list_conversations(limit=100)
    selected_id = st.session_state.get("qa_conversation_id")
    matching_ids = {item["id"] for item in conversations}
    if selected_id not in matching_ids:
        st.session_state.pop("qa_conversation_id", None)
        selected_id = None
    if st.sidebar.button("＋ New conversation", use_container_width=True):
        st.session_state.pop("qa_conversation_id", None)
        st.session_state["qa_picker_version"] = st.session_state.get("qa_picker_version", 0) + 1
        st.rerun()
    if conversations:
        labels = {
            item["id"]: f'{item["title"]} · {item["updated_at"][:16].replace("T", " ")}'
            for item in conversations
        }
        picker_key = f"qa-conversation-picker-{st.session_state.get('qa_picker_version', 0)}"
        selected_id = st.sidebar.selectbox(
            "Conversation",
            options=[None] + [item["id"] for item in conversations],
            format_func=lambda value: "New conversation" if value is None else labels[value],
            index=0 if selected_id is None else [item["id"] for item in conversations].index(selected_id) + 1,
            key=picker_key,
        )
        if selected_id:
            st.session_state["qa_conversation_id"] = selected_id
        else:
            st.session_state.pop("qa_conversation_id", None)
    return st.session_state.get("qa_conversation_id")


def _show_chat_messages(conversation_id):
    if not conversation_id:
        return
    for message in get_messages(conversation_id):
        with st.chat_message(message["role"]):
            st.markdown(message["content"])
            if message["role"] == "user":
                language_note = f"Detected language: {message['detected_language'] or 'Unknown'}"
                if message["language_confidence"] is not None:
                    language_note += f" · Detector score: {message['language_confidence']:.0%}"
                if message["input_language"] and message["input_language"] != message["detected_language"]:
                    language_note += f" · Selected input language: {message['input_language']}"
                st.caption(language_note)
            if message["role"] == "assistant":
                feedback = message["feedback"]
                if feedback is None:
                    columns = st.columns(2)
                    if columns[0].button("Helpful", key=f"helpful-{message['id']}"):
                        set_feedback(message["id"], True)
                        st.rerun()
                    if columns[1].button("Not helpful", key=f"not-helpful-{message['id']}"):
                        set_feedback(message["id"], False)
                        st.rerun()
                else:
                    st.caption("Feedback recorded.")


def _render_question_page(conversation_id):
    st.title("Ask a Question")
    st.caption("Question, context, and a limited recent conversation history are sent to Groq.")
    _show_chat_messages(conversation_id)
    with st.form("qa-question-form"):
        question = st.text_area("Your question", height=110)
        input_language = st.selectbox(
            "Question language",
            ["Automatic detection"] + LANGUAGE_CHOICES,
        )
        answer_language = st.selectbox("Answer language", ANSWER_LANGUAGES)
        answer_detail = st.select_slider(
            "Answer detail",
            options=["Short", "Medium", "Detailed"],
            value="Medium",
        )
        mode = st.radio(
            "Answer mode",
            ["General Knowledge", "Context-Only"],
            horizontal=True,
            help="Context-Only answers solely from the supplied text and states when it is missing.",
        )
        context = st.text_area("Optional context", height=150)
        with st.expander("Advanced generation options"):
            temperature = st.slider("Temperature", 0.0, 2.0, 0.2, 0.1)
            max_tokens = st.slider("Maximum output tokens", 128, 4096, 1024, 128)
        submit = st.form_submit_button("Get answer", type="primary")
    if not submit:
        return
    if not question.strip():
        st.error("Enter a question before continuing.")
        return
    detected = detect_language(question)
    selected_language = detected["name"] if input_language == "Automatic detection" else input_language
    history = []
    if conversation_id:
        history = [
            {"role": item["role"], "content": item["content"]}
            for item in get_messages(conversation_id, limit=12)
        ]
    with st.spinner("Generating an answer..."):
        try:
            answer = answer_question(
                question=question,
                answer_language=answer_language,
                question_language=selected_language,
                answer_detail=answer_detail,
                mode=mode,
                context=context,
                history=history,
                temperature=temperature,
                max_output_tokens=max_tokens,
            )
            is_new_conversation = conversation_id is None
            conversation_id = conversation_id or create_conversation(question[:120])
            save_exchange(
                conversation_id,
                question.strip(),
                answer,
                detected["name"],
                selected_language,
                answer_language,
                language_confidence=detected["confidence"],
            )
        except (ValueError, GroqServiceError) as error:
            st.error(str(error))
            return
    st.session_state["qa_conversation_id"] = conversation_id
    if is_new_conversation:
        st.session_state["qa_picker_version"] = st.session_state.get("qa_picker_version", 0) + 1
    st.rerun()


def _render_translation():
    st.title("Translation Studio")
    st.caption("Translation quality can vary; review important or sensitive translations.")
    source_key = "qa-translation-source"
    target_key = "qa-translation-target"
    if st.button("⇄ Swap source and target languages"):
        source_value = st.session_state.get(source_key, "Automatic detection")
        target_value = st.session_state.get(target_key, "English")
        if source_value == "Automatic detection":
            st.warning("Choose a specific source language before swapping.")
        else:
            st.session_state[source_key] = target_value
            st.session_state[target_key] = source_value
            st.rerun()
    with st.form("translation-form"):
        text = st.text_area("Text to translate", height=220)
        columns = st.columns(2)
        source = columns[0].selectbox(
            "Source language",
            ["Automatic detection"] + LANGUAGE_CHOICES,
            key=source_key,
        )
        target = columns[1].selectbox(
            "Target language",
            LANGUAGE_CHOICES,
            index=0,
            key=target_key,
        )
        submit = st.form_submit_button("Translate", type="primary")
    if submit:
        if not text.strip():
            st.error("Enter text to translate.")
            return
        detected = detect_language(text) if source == "Automatic detection" else None
        source_name = detected["name"] if detected else source
        with st.spinner("Translating..."):
            try:
                translation = translate_text(text, source, target)
            except (ValueError, GroqServiceError) as error:
                st.error(str(error))
                return
        st.subheader(f"Translation · {source_name} to {target}")
        st.text_area("Translated text", value=translation, height=220)
        st.code(translation)


def _render_summarization():
    st.title("Text Summarization")
    st.caption("The full submitted text is sent to Groq; input is not silently truncated.")
    with st.form("summary-form"):
        text = st.text_area("Text to summarize", height=260)
        columns = st.columns(3)
        style = columns[0].selectbox("Summary style", ["Short", "Detailed", "Bullet points"])
        language = columns[1].selectbox("Summary language", SUMMARY_LANGUAGES)
        length = columns[2].text_input("Desired length", "About 5 sentences", max_chars=200)
        submit = st.form_submit_button("Summarize", type="primary")
    if submit:
        if not text.strip():
            st.error("Enter text to summarize.")
            return
        with st.spinner("Summarizing..."):
            try:
                summary = summarize_text(text, style, language, length)
            except (ValueError, GroqServiceError) as error:
                st.error(str(error))
                return
        st.subheader("Summary")
        st.markdown(summary)


def _render_history():
    st.title("Conversation History")
    search = st.text_input("Search conversation titles and messages")
    conversations = list_conversations(search=search, limit=200)
    if not conversations:
        st.info("No matching saved conversations.")
        return
    for conversation in conversations:
        with st.expander(
            f"{conversation['title']} · {conversation['updated_at'][:16].replace('T', ' ')}"
        ):
            for message in get_messages(conversation["id"]):
                st.markdown(f"**{'You' if message['role'] == 'user' else 'Assistant'}**")
                st.write(message["content"])
            if st.button("Delete conversation", key=f"delete-{conversation['id']}"):
                delete_conversation(conversation["id"])
                if st.session_state.get("qa_conversation_id") == conversation["id"]:
                    st.session_state.pop("qa_conversation_id", None)
                st.session_state["qa_picker_version"] = st.session_state.get("qa_picker_version", 0) + 1
                st.rerun()


def _render_settings():
    st.title("Settings")
    st.subheader("Groq API configuration")
    if groq_is_configured():
        st.success("Groq API configuration detected.")
    else:
        st.warning("API key not configured. Add GROQ_API_KEY to this project's .env file.")
    st.write("Configured model:", get_groq_model())
    st.caption("The API key is never displayed or stored in the conversation database.")
    if st.button("Test Groq connection"):
        with st.spinner("Checking the Groq connection..."):
            try:
                create_chat_completion(
                    [{"role": "user", "content": "Reply with the single word OK."}],
                    temperature=0.2,
                    max_output_tokens=16,
                )
            except GroqServiceError as error:
                st.error(str(error))
            else:
                st.success("Groq connection succeeded.")
    st.divider()
    st.subheader("Local conversation data")
    st.caption("Conversation history is stored locally in SQLite and can be deleted here.")
    confirm = st.checkbox("I understand that clearing history permanently deletes all conversations.")
    if st.button("Clear all conversation history", disabled=not confirm):
        deleted = clear_history()
        st.session_state.pop("qa_conversation_id", None)
        st.success(f"Deleted {deleted} conversations.")
        st.rerun()
    st.info(
        "Questions sent for answers, translation, or summarization are processed by Groq's "
        "external API. Review sensitive text before submitting it."
    )


def render_app(embed=False):
    if not embed:
        st.set_page_config(
            page_title="Multilingual Question Answering",
            page_icon="🌐",
            layout="wide",
        )
    try:
        initialize_database()
    except (OSError, sqlite3.Error):
        st.error("Could not initialize the local conversation database. Check its path and permissions.")
        st.stop()
    st.sidebar.title("Multilingual Q&A")
    page = st.sidebar.radio("Navigate", NAVIGATION, key="multilingual-qa-navigation")
    conversation_id = _select_conversation() if page == "Ask a Question" else None
    page_renderers = {
        "Home": _render_home,
        "Ask a Question": lambda: _render_question_page(conversation_id),
        "Translation Studio": _render_translation,
        "Text Summarization": _render_summarization,
        "Conversation History": _render_history,
        "Settings": _render_settings,
    }
    try:
        page_renderers[page]()
    except (OSError, sqlite3.Error):
        st.error("Could not access the local conversation database. Check its path and permissions.")
